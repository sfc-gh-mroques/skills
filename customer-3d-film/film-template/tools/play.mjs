// Real-playback smoke test (no test hooks): poster → warm-up → play → pause/seek/keys. Reports console errors.
// usage: node tools/play.mjs [--w 960] [--h 540] [--backend webgl] [--out tmp/play] [--file index.html]
import fs from 'fs';
import { launch, URL } from './browser.mjs';
const args = process.argv.slice(2);
const opt = (k, d) => { const i = args.indexOf(`--${k}`); return i >= 0 ? args[i + 1] : d; };
const W = +opt('w', 960), H = +opt('h', 540), backend = opt('backend', 'webgpu'), out = opt('out', 'tmp/play'), file = opt('file', 'index.html');
fs.mkdirSync(out, { recursive: true });
const browser = await launch();
const page = await browser.newPage({ viewport: { width: W, height: H }, deviceScaleFactor: 1 });
const logs = [];
page.on('console', (m) => { const t = m.text(); if (!/GroupMarkerNotSet|experimental on this platform|Automatic fallback to software/.test(t)) logs.push(`${m.type()}: ${t.slice(0, 500)}`); });
page.on('pageerror', (e) => logs.push('PAGEERROR ' + String(e.stack || e).slice(0, 900)));
if (backend === 'webgl') await page.addInitScript(() => { window.__forceWebGL = true; });
await page.addInitScript(() => { window.__quality = 'low'; });
const t0 = Date.now();
await page.goto(URL.replace(/[^/]*$/, file));
await page.waitForTimeout(1500);
await page.screenshot({ path: `${out}/0_loading.png`, timeout: 240000 });
await page.waitForFunction(() => window.__ready !== undefined && window.__ready !== false, null, { timeout: 900000 }).catch(() => logs.push('TIMEOUT waiting ready'));
console.log('ready in', ((Date.now() - t0) / 1000).toFixed(1), 's →', await page.evaluate(() => window.__ready), '| backend:', await page.evaluate(() => (window.__film.E.renderer.backend.isWebGPUBackend ? 'webgpu' : 'webgl2')));
await page.waitForTimeout(1500);
await page.screenshot({ path: `${out}/1_poster.png`, timeout: 240000 });
const state = () => page.evaluate(() => ({ t: +window.__film.film.time.toFixed(2), playing: window.__film.film.playing, bar: document.querySelector('.bar').classList.contains('show'), poster: document.querySelector('.poster').hidden }));
await page.click('#film-play');
await page.waitForTimeout(9000);
console.log('after play 9 s   ', JSON.stringify(await state()));
await page.screenshot({ path: `${out}/2_playing.png`, timeout: 240000 });
await page.keyboard.press('Space');
await page.waitForTimeout(600);
const paused = await state();
await page.waitForTimeout(1500);
console.log('space → paused   ', JSON.stringify(paused), '→', JSON.stringify(await state()));
await page.keyboard.press('ArrowRight'); await page.waitForTimeout(400);
await page.keyboard.press('ArrowRight'); await page.waitForTimeout(1500);
console.log('→ → chapters     ', JSON.stringify(await state()));
await page.screenshot({ path: `${out}/3_chapter.png`, timeout: 240000 });
const box = await page.locator('#film-track').boundingBox();
await page.mouse.click(box.x + box.width * 0.8, box.y + box.height / 2);
await page.waitForTimeout(2500);
console.log('scrub to 80 %    ', JSON.stringify(await state()));
await page.screenshot({ path: `${out}/4_scrub.png`, timeout: 240000 });
await page.keyboard.press('Space');
await page.waitForTimeout(6000);
console.log('play again 6 s   ', JSON.stringify(await state()));
await page.evaluate(() => { window.__film.film.time = window.__film.film.duration - 1.2; });
await page.waitForTimeout(5000);
console.log('at the end       ', JSON.stringify(await state()));
await page.screenshot({ path: `${out}/5_end.png`, timeout: 240000 });
console.log(logs.length ? '--- console ---\n' + [...new Set(logs)].slice(0, 30).join('\n') : 'console: clean');
await browser.close();
